-- Banco criado com este script? Depois rode: python manage.py migrate --fake-initial
-- Banco vazio? Basta: python manage.py migrate (o Django cria as tabelas).
--
-- Valores aceitos (conferidos pela aplicação, não por CHECK no banco):
--   usuario.perfil           GESTOR | MOTORISTA
--   *.situacao               ATIVO | INATIVO   (usuario, motorista, veiculo, plano_manutencao)
--   leitura_odometro.origem  MANUAL | ORDEM_SERVICO | AJUSTE_ODOMETRO
--   ordem_servico.status     ABERTA | APROVADA | CONCLUIDA | CANCELADA
-- =====================================================================

CREATE TABLE empresa (
    cnpj          varchar(14)  NOT NULL,
    razao_social  varchar(120) NOT NULL,
    telefone      varchar(15)  NOT NULL,
    email         varchar(120) NOT NULL,
    CONSTRAINT pk_empresa PRIMARY KEY (cnpj)
);

CREATE TABLE usuario (
    email          varchar(120) NOT NULL,
    nome           varchar(120),            -- vazio no perfil MOTORISTA: vem do cadastro do motorista
    senha          varchar(255) NOT NULL,   -- hash bcrypt, nunca texto puro
    perfil         varchar(20)  NOT NULL,
    situacao       varchar(20)  NOT NULL,
    cnpj_empresa   varchar(14)  NOT NULL,
    cpf_motorista  varchar(11),             -- obrigatório no perfil MOTORISTA, vazio no GESTOR
    CONSTRAINT pk_usuario PRIMARY KEY (email),
    CONSTRAINT uq_usuario_cpf_motorista UNIQUE (cpf_motorista)
);

CREATE TABLE motorista (
    cpf           varchar(11)  NOT NULL,
    nome          varchar(120) NOT NULL,
    telefone      varchar(15)  NOT NULL,
    num_cnh       varchar(11)  NOT NULL,
    validade_cnh  date         NOT NULL,
    situacao      varchar(20)  NOT NULL,
    cnpj_empresa  varchar(14)  NOT NULL,
    CONSTRAINT pk_motorista PRIMARY KEY (cpf)
);

CREATE TABLE veiculo (
    placa         varchar(8)  NOT NULL,
    marca         varchar(50) NOT NULL,
    modelo        varchar(60) NOT NULL,
    ano           integer     NOT NULL,
    tipo          varchar(30) NOT NULL,
    situacao      varchar(20) NOT NULL,
    cnpj_empresa  varchar(14) NOT NULL,
    CONSTRAINT pk_veiculo PRIMARY KEY (placa)
);

CREATE TABLE plano_manutencao (
    id_plano         integer GENERATED BY DEFAULT AS IDENTITY,
    descricao        varchar(120) NOT NULL,
    tipo_veiculo     varchar(30)  NOT NULL,
    intervalo_km     integer,
    intervalo_meses  integer,
    situacao         varchar(20)  NOT NULL,
    cnpj_empresa     varchar(14)  NOT NULL,
    CONSTRAINT pk_plano_manutencao PRIMARY KEY (id_plano)
);

CREATE TABLE leitura_odometro (
    codigo         integer GENERATED BY DEFAULT AS IDENTITY,
    data_leitura   date         NOT NULL,
    origem         varchar(20)  NOT NULL,
    placa_veiculo  varchar(8)   NOT NULL,
    quilometragem  integer      NOT NULL,
    email_usuario  varchar(120) NOT NULL,   -- quem lançou a leitura
    CONSTRAINT pk_leitura_odometro PRIMARY KEY (codigo)
);

CREATE TABLE ordem_servico (
    id_ordem         integer GENERATED BY DEFAULT AS IDENTITY,
    numero           integer       NOT NULL, -- sequencial dentro da empresa, gerado pela aplicação
    descricao        varchar(255)  NOT NULL,
    data_abertura    date          NOT NULL,
    data_conclusao   date,
    quilometragem    integer,
    status           varchar(20)   NOT NULL,
    oficina          varchar(120),
    valor            numeric(10,2),
    placa_veiculo    varchar(8)    NOT NULL,
    id_plano         integer,
    email_emitente   varchar(120)  NOT NULL,
    email_aprovador  varchar(120),
    CONSTRAINT pk_ordem_servico PRIMARY KEY (id_ordem)
);

-- Chaves estrangeiras (sem ON DELETE: o banco recusa excluir registro com histórico)
